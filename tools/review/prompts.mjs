const nameLine = (label, t) => `${label}: 본문 표기 「${t.name}」, 정식 팀명 「${t.full ?? t.name}」`;

/** 쓰는 AI 에 보내는 첫 메시지. 리그명·팀명 표기·원본 기록. */
export function writerMessage(facts) {
  const league = LEAGUES[facts.league]?.titleName ?? facts.league;
  const draw = facts.score.home === facts.score.away;
  return [
    `리그: ${league}`,
    `경기 날짜: ${facts.date}`,
    nameLine('홈 팀', facts.home),
    nameLine('원정 팀', facts.away),
    `결과: ${facts.away.name} ${facts.score.away} - ${facts.score.home} ${facts.home.name}${draw ? ' (무승부)' : ''}`,
    '',
    '원본 기록(JSON):',
    JSON.stringify(facts.ai),
  ].join('\n');
}

const issueLine = (i) => `- [${i.field ?? '?'}] ${i.quote ? `「${i.quote}」 — ` : ''}${i.problem ?? ''}${i.fix ? ` → 고칠 방향: ${i.fix}` : ''}`;

/** 재작성 메시지: 첫 메시지 + 앞선 원고 + 지적 목록(코드 검사·검토자 모두). */
export function rewriteMessage(facts, prevDoc, issues) {
  return [
    writerMessage(facts),
    '',
    '앞서 쓴 원고(JSON):',
    prevDoc ? JSON.stringify(prevDoc) : '(올바른 JSON 이 아니었다)',
    '',
    '아래 지적을 모두 고쳐 처음부터 다시 쓴다. 지적되지 않은 부분도 같은 규칙을 지킨다.',
    ...issues.map(issueLine),
  ].join('\n');
}

/** 검토 AI 에 보내는 메시지: 원본 기록 + 리뷰 문서. */
export function reviewerMessage(facts, doc) {
  return [
    writerMessage(facts),
    '',
    '검토할 리뷰(JSON):',
    JSON.stringify(doc),
  ].join('\n');
}
